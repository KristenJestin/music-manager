/**
 * Record the four matching scenarios from the real MusicBrainz.
 *
 * `bun run scripts/record-matching-cassettes.ts [name…] [--dry]`
 *
 * Run **once**, by hand, with `MM_MB_CONTACT` set. It writes two things per scenario:
 *
 *  - `apps/web/test/cassettes/matching/<name>.json` — every MusicBrainz document one match
 *    touches, under the exact cache key `integrations/musicbrainz.ts` computes for it. Seeding
 *    those rows and running the service `offline` replays the match without a socket.
 *  - `packages/domain/fixtures/matching/<name>.json` — the same documents reduced to the pure
 *    engine's input, so `packages/domain` can test the scoring without importing anything from
 *    `apps/web`.
 *
 * It obeys the one-request-per-second rule itself rather than borrowing the app's limiter,
 * because it must run without a database and the limiter lives behind the cache. The contact
 * is read from the environment and never printed: the User-Agent is the one thing MusicBrainz
 * asks for and the one thing that must not end up in a committed file.
 *
 * The requests it makes are exactly the ones the service makes, in the same order, decided by
 * the same pure engine — the top-N lookups are chosen by pre-scoring the search results here
 * too. A cassette is therefore a recording of the real algorithm's appetite, not a guess at it.
 */
