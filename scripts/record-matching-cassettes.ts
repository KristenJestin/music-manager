interface SingleScenario {
  readonly name: string;
  readonly kind: "single";
  readonly source: { url: string; note?: string };
  readonly video: MatchVideo;
  /**
   * Other videos the same cassette must be able to answer.
   *
   * `videos[0]` is the scenario the phase table describes and the only one the pure-engine
   * fixture is built from — deliberately *not* what the toolbox fixture serves, which is the
   * whole point of a cassette that needs neither Docker nor a network. But the Console's
   * wizard resolves through the toolbox, so on `fixture://skinny-love` it matches the *other*
   * video, with a different artist clause and a different duration window, and the cassette
   * had no document for it: step 2 of a single could not be exercised offline at all
   * (DRIVE-1 §A1, when a spec was finally written for it). Recording both keeps the scenario
   * and makes the fixture pair usable end to end.
   */
  readonly alsoVideos?: readonly MatchVideo[];
}

type Scenario = AlbumScenario | SingleScenario;

interface AlbumCommon {
  readonly album: string;
  readonly artist: string;
  readonly year: number;
  readonly uploader: string;
  readonly label: string;
  readonly releasedOn: string;
}

/**
 * The "Auto-generated by YouTube" blurb, in the exact shape `normalize/youtube-description.ts`
 * parses. It is the only place the label and the exact release date ever appear, which is why
 * the matcher reads it at all.
 */
function autoDescription(of: AlbumCommon & { track: string }): string {
  return [
    `Provided to YouTube by ${of.label}`,
    "",
    `${of.track} · ${of.artist}`,
    "",
    of.album,
    "",
    `℗ ${String(of.year)} ${of.label}`,
    "",
    `Released on: ${of.releasedOn}`,
    "",
    "Auto-generated by YouTube.",
  ].join("\n");
}

/** Build an album's video list from `[title, seconds]` pairs, all sharing the YouTube tags. */
function albumVideos(
  entries: readonly (readonly [string, number, string?])[],
  common: AlbumCommon,
): MatchVideo[] {
  return entries.map(([title, duration, trackTag], index) => ({
    id: `yt-${common.album.toLowerCase().replace(/\W+/g, "-")}-${String(index + 1)}`,
    index,
    title,
    durationSeconds: duration,
    uploader: common.uploader,
    ytTrack: trackTag ?? title,
    ytArtist: common.artist,
    ytAlbum: common.album,
    ytReleaseYear: common.year,
    description: autoDescription({ ...common, track: trackTag ?? title }),
  }));
}

