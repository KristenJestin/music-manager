/* recording                                                           */
/* ------------------------------------------------------------------ */

interface CassetteEntry {
  readonly key: string;
  readonly payload: unknown;
}

interface SearchResult {
  readonly releases?: readonly MbRelease[];
  readonly recordings?: readonly MbRecording[];
  readonly "release-groups"?: readonly { id?: string; title?: string }[];
}

const SEARCH_LIMIT = 25;

/**
 * How many lookups are recorded, against the six a match spends.
 *
 * The margin is not slack in the budget — the service still stops at `matchLookupLimit`. It is
 * insurance for the replay: the six a match picks are decided by a pre-score, and a pre-score
 * shifts when a duration is corrected or a preference is changed. Recording ten means such a
 * change moves the ranking instead of breaking every cassette test at once.
 */
const RECORDED_LOOKUPS = DEFAULT_LOOKUP_LIMIT + 4;

async function recordAlbum(scenario: AlbumScenario): Promise<{
  entries: CassetteEntry[];
  fixture: unknown;
}> {
  const entries: CassetteEntry[] = [];
  // Derived exactly as `match` and `mm match` derive them. Deriving them differently here is
  // what made the first recording unreplayable: a label read in one place and left null in the
  // other reordered two near-identical pressings and sent the lookups to different candidates.
  const hints = albumHints(scenario.videos);

  // 1 — the release group.
  const groupQuery = lucene.releaseGroupQuery(scenario.source.album, scenario.source.artist);
  const groups = await get<SearchResult>("release-group", {
    query: groupQuery,
    limit: String(SEARCH_LIMIT),
    offset: "0",
  });
  entries.push({
    key: `search/release-group?query=${groupQuery}&limit=${String(SEARCH_LIMIT)}&offset=0`,
    payload: groups,
  });

  const best = (groups["release-groups"] ?? [])[0];
  if (best?.id === undefined) throw new Error(`no release group for ${scenario.name}`);

  // 2 — the releases of that group.
  const releaseQuery = lucene.releaseQuery({
    album: scenario.source.album,
    releaseGroupId: best.id,
  });
  const releases = await get<SearchResult>("release", {
    query: releaseQuery,
    limit: String(SEARCH_LIMIT),
    offset: "0",
  });
  entries.push({
    key: `search/release?query=${releaseQuery}&limit=${String(SEARCH_LIMIT)}&offset=0`,
    payload: releases,
  });

  // 3 — the N the engine would look up, decided by the engine itself.
  const shallow = (releases.releases ?? []).map((release) => ({ release, detailed: false }));
  const prescored = releaseCandidates.score({
    videos: scenario.videos,
    hints,
    candidates: shallow,
  });
  const wanted = prescored.candidates
    .slice(0, RECORDED_LOOKUPS)
    .map((candidate) => candidate.id)
    .filter((id) => id !== "");

  const detailed: MbRelease[] = [];
  for (const mbid of wanted) {
    const full = await get<MbRelease>(`release/${mbid}`, { inc: INC.releaseFull });
    entries.push({ key: `release/${mbid}?inc=releaseFull`, payload: full });
    detailed.push(full);
  }

  const detailedIds = new Set(detailed.map((release) => release.id));
  const fixture = {
    kind: "album",
    videos: scenario.videos,
    hints,
    candidates: (releases.releases ?? []).map((release) => {
      const full = detailed.find((candidate) => candidate.id === release.id);
      return full === undefined ? { release, detailed: false } : { release: full, detailed: true };
    }),
    lookedUp: [...detailedIds],
  };

  return { entries, fixture };
}

async function recordSingle(scenario: SingleScenario): Promise<{
  entries: CassetteEntry[];
  fixture: unknown;
}> {
  const entries: CassetteEntry[] = [];
  const video = scenario.video;
  const title = video.ytTrack ?? video.title;

  // The same two searches the service makes: narrow to find the answer, wide to surface the
  // same-title recordings by other artists that the score has to be seen rejecting.
  const narrow = lucene.recordingQuery({
    title,
    artist: video.ytArtist ?? video.uploader ?? null,
    durationSeconds: video.durationSeconds,
  });
  const wide = lucene.recordingQuery({ title });

  const merged: MbRecording[] = [];
  const seen = new Set<string>();
  for (const query of [narrow, wide]) {
    const found = await get<SearchResult>("recording", {
      query,
      limit: String(SEARCH_LIMIT),
      offset: "0",
    });
    entries.push({
      key: `search/recording?query=${query}&limit=${String(SEARCH_LIMIT)}&offset=0`,
      payload: found,
    });
    for (const recording of found.recordings ?? []) {
      if (recording.id === undefined || seen.has(recording.id)) continue;
      seen.add(recording.id);
      merged.push(recording);
    }
  }

  const candidates: unknown[] = [];
  for (const [index, recording] of merged.entries()) {
    if (recording.id === undefined) continue;
    let releases = (recording as { releases?: readonly MbRelease[] }).releases ?? [];
    if (index < RECORDED_LOOKUPS) {
      const full = await get<MbRecording & { releases?: readonly MbRelease[] }>(
        `recording/${recording.id}`,
        { inc: `${INC.recordingFull}+releases+release-groups+media` },
      );
      entries.push({ key: `recording/${recording.id}?inc=recordingFull`, payload: full });
      if (full.releases !== undefined) releases = full.releases;
    }
    const credited = recording["artist-credit"] ?? [];
    candidates.push({
      id: recording.id,
      title: recording.title ?? "",
      artist: credited
        .map((entry) => `${entry.name ?? entry.artist?.name ?? ""}${entry.joinphrase ?? ""}`)
        .join("")
        .trim(),
      disambiguation: recording.disambiguation ?? "",
      lengthMs: recording.length ?? null,
      isrcs: recording.isrcs ?? [],
      searchScore: (recording as { score?: number }).score ?? null,
      releases,
    });
  }

  return { entries, fixture: { kind: "single", video, candidates } };
}

