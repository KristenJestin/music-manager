const CASSETTE_DIR = join(repoRoot, "apps", "web", "test", "cassettes", "matching");
const FIXTURE_DIR = join(repoRoot, "packages", "domain", "fixtures", "matching");

function writeJson(path: string, value: unknown): void {
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`, "utf8");
}

/** The documents a previous run of this scenario already recorded, by cache key. */
function existingCassette(name: string): Map<string, unknown> {
  const path = join(CASSETTE_DIR, `${name}.json`);
  if (!existsSync(path)) return new Map();
  const parsed = JSON.parse(readFileSync(path, "utf8")) as {
    entries?: readonly { key: string; payload: unknown }[];
  };
  return new Map((parsed.entries ?? []).map((entry) => [entry.key, entry.payload]));
}

async function main(): Promise<void> {
  const wanted = process.argv.slice(2).filter((arg) => !arg.startsWith("--"));
  const dry = process.argv.includes("--dry");
  const chosen = wanted.length === 0 ? SCENARIOS : SCENARIOS.filter((s) => wanted.includes(s.name));
  if (chosen.length === 0) {
    console.error(`unknown scenario. Known: ${SCENARIOS.map((s) => s.name).join(", ")}`);
    process.exit(1);
  }

  mkdirSync(CASSETTE_DIR, { recursive: true });
  mkdirSync(FIXTURE_DIR, { recursive: true });
  const recordedAt = new Date().toISOString();

  for (const scenario of chosen) {
    console.log(`recording ${scenario.name}…`);
    /*
     * Documents already in the cassette are kept rather than re-fetched.
     *
     * A cassette is a recording of one afternoon's MusicBrainz. Adding a video to a scenario
     * must add the documents that video needs and change nothing else — otherwise every
     * assertion written against the old recording is re-litigated by a run that was only ever
     * meant to be additive. `--refresh` is the way to ask for the other thing.
     */
    const previous = existingCassette(scenario.name);
    const known = process.argv.includes("--refresh") ? new Map<string, unknown>() : previous;
    const gathered: CassetteEntry[] = [];
    let entries: CassetteEntry[];
    let fixture: unknown;
    try {
      ({ entries, fixture } =
        scenario.kind === "album"
          ? await recordAlbum(scenario, known, gathered)
          : await recordSingle(scenario, known, gathered));
    } catch (error) {
      /*
       * Keep what was fetched, then re-raise.
       *
       * Every document here cost a second and none of them will ever change under this key, so
       * a run that MusicBrainz's load-shedder interrupts must not make the next one start from
       * zero — `existingCassette` reads exactly this file back as `known`. The *fixture* is
       * deliberately not written: it is derived from the whole set, and half of one would be a
       * ranking nobody recorded.
       */
      if (!dry && gathered.length > 0) {
        writeJson(join(CASSETTE_DIR, `${scenario.name}.json`), {
          name: scenario.name,
          kind: scenario.kind,
          recordedAt,
          source: scenario.source,
          videos: scenario.kind === "album" ? scenario.videos : [scenario.video],
          entries: gathered,
          partial: true,
        });
        console.log(
          `  interrupted — ${String(gathered.length)} document(s) kept; run it again to resume`,
        );
      }
      throw new PartialRecording(gathered, error);
    }

    const cassette = {
      name: scenario.name,
      kind: scenario.kind,
      recordedAt,
      source: scenario.source,
      videos: scenario.kind === "album" ? scenario.videos : [scenario.video],
      entries,
    };

    if (dry) {
      console.log(`  ${String(entries.length)} document(s), not written (--dry)`);
      continue;
    }
    writeJson(join(CASSETTE_DIR, `${scenario.name}.json`), cassette);
    writeJson(join(FIXTURE_DIR, `${scenario.name}.json`), fixture);
    console.log(`  ${String(entries.length)} document(s) written`);
  }

  console.log(`\n${String(requests)} MusicBrainz request(s), at most one per second.`);
}

await main();
