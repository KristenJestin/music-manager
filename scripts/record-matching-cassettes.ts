interface SearchResult {
  readonly releases?: readonly MbRelease[];
  readonly recordings?: readonly MbRecording[];
  readonly "release-groups"?: readonly { id?: string; title?: string }[];
}

const SEARCH_LIMIT = 25;

/**
 * How many lookups are recorded, against the ceiling a match is allowed.
 *
 * The margin is not slack in the budget — the service stops when its branch and bound says
 * stop, well short of `matchLookupLimit` on every scenario here. It is insurance for the
 * replay: the ones a match opens are chosen by an attainable score, and that shifts when a
 * duration is corrected or a weight is moved, so recording four more than the ceiling means
 * such a change *moves a ranking* instead of breaking every cassette test at once with
 * "no document for …".
 */
const RECORDED_LOOKUPS = DEFAULT_LOOKUP_LIMIT + 4;

/**
 * Record an album scenario, following the **two-level** search of decision 151.
 *
 * One `release-group` search, one `release` search per group kept, and a tracklist lookup for
 * the ones the engine itself would spend them on — with the same "one reserved per group"
 * allocation `matching.service.ts` uses, so a cassette stays a recording of the real
 * algorithm's appetite rather than a guess at it.
 *
 * `known` is what a previous run already recorded. Documents already on the cassette are
 * **reused**, never re-fetched: adding a per-group search to the algorithm must add the
 * documents that search needs and change nothing else, or every assertion written against the
 * old recording is silently re-litigated by an afternoon of a different MusicBrainz.
 * `--refresh` is how you ask for the other thing.
 */
async function recordAlbum(
  scenario: AlbumScenario,
  known: ReadonlyMap<string, unknown> = new Map(),
  entries: CassetteEntry[] = [],
): Promise<{ entries: CassetteEntry[]; fixture: unknown }> {
  const written = new Set<string>();
  // Derived exactly as `match` and `mm match` derive them. Deriving them differently here is
  // what made the first recording unreplayable: a label read in one place and left null in the
  // other reordered two near-identical pressings and sent the lookups to different candidates.
  const base0 = albumHints(scenario.videos);
  const hints = { ...base0, edition: [...(base0.edition ?? [])] };

  async function document<T>(key: string, path: string, query: Record<string, string>): Promise<T> {
    const cached = known.get(key);
    const payload = cached ?? (await get<T>(path, query));
    if (!written.has(key)) {
      written.add(key);
      entries.push({ key, payload });
    }
    return payload as T;
  }

  async function searchDocument(
    entity: "release" | "release-group" | "recording",
    query: string,
  ): Promise<SearchResult> {
    return await document<SearchResult>(
      `search/${entity}?query=${query}&limit=${String(SEARCH_LIMIT)}&offset=0`,
      entity,
      { query, limit: String(SEARCH_LIMIT), offset: "0" },
    );
  }

  /*
   * 1 — the release groups, down the same ladder `findReleaseGroups` climbs.
   *
   * First credited artist, then the whole credit, then the base title, then **each of the
   * other names the source credits** and the bare base title — and never the title on its own,
   * which is the rung the sixth owner review had removed. The recording-convergence rung below
   * it is recorded too, because a scenario that needs it (Laufey's *Bewitched*) has to replay
   * through it rather than around it.
   *
   * This list is a copy of the service's, and it has to stay one: a cassette is a recording of
   * the real algorithm's appetite, and a recorder that asked a different set of questions would
   * be a recording of a matcher nobody ships. `matching.service.test.ts` is what notices when
   * the two drift, by failing with "no document for …" rather than with a moved ranking.
   */
  const album = scenario.source.album;
  const credit = scenario.source.artist;
  const primary = primaryArtist(credit);
  const base = stripEditionQualifier(album);
  const bare = stripEditionQualifierLoosely(album);

  const rungs = [lucene.releaseGroupQuery(album, primary ?? credit)];
  if (primary !== null) rungs.push(lucene.releaseGroupQuery(album, credit));
  if (base !== album) rungs.push(lucene.releaseGroupQuery(base, primary ?? credit));
  for (const name of artistLadder(credit, CREDIT_LADDER_LIMIT).slice(2)) {
    rungs.push(lucene.releaseGroupQuery(album, name));
    if (base !== album) rungs.push(lucene.releaseGroupQuery(base, name));
  }
  if (bare !== base && bare !== album) {
    rungs.push(lucene.releaseGroupQuery(bare, primary ?? credit));
  }

  let rawGroups: readonly { id?: string; title?: string }[] = [];
  /** The rung that answered, so the fixture's hints are the ones the service would score with. */
  let answeredRung: string | null = null;
  for (const rung of rungs) {
    const answer = await searchDocument("release-group", rung);
    rawGroups = answer["release-groups"] ?? [];
    if (rawGroups.length > 0) {
      answeredRung = rung;
      break;
    }
  }

  /*
   * The bare rung, having answered, proves the trailing word was an edition after all.
   *
   * `editionProvenByFallback` in `matching.service.ts` does exactly this, for exactly the
   * reason written there, and the fixture has to carry the hints the service would score with
   * or the pure-engine test and the service test disagree about *AFTERCARE DELUXE* by 0.27.
   */
  if (answeredRung !== null && bare !== base && bare !== album) {
    if (answeredRung === lucene.releaseGroupQuery(bare, primary ?? credit)) {
      for (const token of editionTokensIn(album.slice(bare.length))) {
        if (!hints.edition.includes(token)) hints.edition.push(token);
      }
    }
  }

  if (rawGroups.length === 0) {
    // The last rung: the album through its tracks. Four searches, the longest videos first,
    // exactly as `convergeThroughRecordings` picks them.
    const sample = [...scenario.videos]
      .sort((a, b) => (b.durationSeconds ?? 0) - (a.durationSeconds ?? 0) || a.index - b.index)
      .slice(0, 4);
    // The same filter `convergeThroughRecordings` applies: only recordings that carry the
    // credit vote, only groups bearing the album's name are counted, and a group needs two
    // distinct tracks to name it. A cassette that recorded a looser answer would replay a
    // ranking the service never computes.
    const converged = new Map<string, { voters: Set<number>; group: MbReleaseGroup }>();
    for (const video of sample) {
      const answer = await searchDocument(
        "recording",
        lucene.recordingQuery({
          title: stripArtistPrefix(video.ytTrack ?? video.title, primary ?? credit),
          artist: primary ?? credit,
          durationSeconds: video.durationSeconds,
        }),
      );
      const seenHere = new Set<string>();
      for (const recording of answer.recordings ?? []) {
        const credited = recording["artist-credit"] ?? [];
        const name = credited
          .map((entry) => `${entry.name ?? entry.artist?.name ?? ""}${entry.joinphrase ?? ""}`)
          .join("")
          .trim();
        if (!creditCarriesArtist(credit, name)) continue;
        for (const release of (recording as { releases?: readonly MbRelease[] }).releases ?? []) {
          const group = release["release-group"];
          const id = group?.id;
          if (group === undefined || id === undefined || seenHere.has(id)) continue;
          const title = group.title ?? release.title ?? "";
          if (titleScore(album, title) < 0.87 && titleScore(base, title) < 0.87) continue;
          seenHere.add(id);
          const entry = converged.get(id) ?? {
            voters: new Set<number>(),
            group: { ...group, "artist-credit": credited } as MbReleaseGroup,
          };
          entry.voters.add(video.index);
          converged.set(id, entry);
        }
      }
    }
    rawGroups = [...converged.values()]
      .filter((entry) => entry.voters.size >= 2)
      .sort((a, b) => b.voters.size - a.voters.size)
      .map((entry) => entry.group);
  }

  /*
   * The artist on its own, which is a search the wizard now offers.
   *
   * "I know the band, not which record" is what somebody types before they can type a title,
   * and `searchReleases` answers it with `releaseGroupQuery("", artist)` — the same builder,
   * with the title clause dropped. Recorded here so the Console's artist-only search replays
   * offline like every other question the matcher can be asked.
   *
   * It is deliberately *after* the ladder: this is not a rung the matcher climbs, it is a
   * question a person asks, and it must never change which groups the recorded match keeps.
   */
  await searchDocument("release-group", lucene.releaseGroupQuery("", primary ?? credit));

  const scoredGroups = releaseGroups.searchScore(rawGroups, hints, scenario.videos.length);
  // One more group than a match keeps, for the same reason as the four extra lookups: a
  // re-scored group must be able to move without breaking every cassette test at once.
  const kept = scoredGroups.slice(0, DEFAULT_GROUP_LIMIT + 1);
  if (kept.length === 0) throw new Error(`no release group for ${scenario.name}`);

  // 2 — the releases of each kept group.
  const searchResults: MbRelease[] = [];
  const seen = new Set<string>();
  const collect = (releases: readonly MbRelease[] | undefined): void => {
    for (const release of releases ?? []) {
      if (release.id === undefined || seen.has(release.id)) continue;
      seen.add(release.id);
      searchResults.push(release);
    }
  };
  for (const group of kept) {
    const query = lucene.releaseQuery({
      album: scenario.source.album,
      releaseGroupId: group.id,
    });
    collect((await searchDocument("release", query)).releases);
  }
  // The service's retry for a record whose every pressing is unofficial: after the whole loop,
  // and only when it produced no release at all. Same condition, same queries, same order.
  if (searchResults.length === 0) {
    for (const group of kept) {
      collect(
        (
          await searchDocument(
            "release",
            lucene.releaseQuery({
              album: scenario.source.album,
              releaseGroupId: group.id,
              officialOnly: false,
            }),
          )
        ).releases,
      );
    }
  }

  /*
   * 3 — the lookups, **in the order the service opens them**, and four more.
   *
   * The order is the whole point and it used to be wrong. The recorder took the top N of the
   * flat pre-score while `exploreReleases` opens by `ceiling` — the best a candidate could
   * still reach — recomputed after every lookup. Those are different lists, so a cassette with
   * eighteen documents could still be missing the fourteenth one a match asks for, and the
   * failure reads "no document for release/…" rather than "the ranking moved".
   *
   * Mirroring the order makes the containment provable instead of likely: the service opens at
   * most `matchLookupLimit` candidates from the head of this exact sequence, and the recorder
   * writes down four more of it. What the recorder does *not* copy is the stopping — it never
   * stops early, because its job is to leave room for a ranking to move.
   */
  const detailedById = new Map<string, MbRelease>();
  const rank = () =>
    releaseCandidates.score({
      videos: scenario.videos,
      hints,
      candidates: searchResults.map((release) => {
        const full = release.id === undefined ? undefined : detailedById.get(release.id);
        return full === undefined
          ? { release, detailed: false }
          : { release: full, detailed: true };
      }),
    });

  const open = async (mbid: string): Promise<void> => {
    const full = await document<MbRelease>(`release/${mbid}?inc=releaseFull`, `release/${mbid}`, {
      inc: INC.releaseFull,
    });
    detailedById.set(mbid, full);
  };

  // One reserved for the best pressing of each group (decision 151), as the service does.
  const seenGroups = new Set<string>();
  for (const candidate of rank().candidates) {
    if (candidate.id === "" || detailedById.size >= RECORDED_LOOKUPS) break;
    const key = candidate.releaseGroupId ?? "";
    if (seenGroups.has(key)) continue;
    seenGroups.add(key);
    await open(candidate.id);
  }

  // Then by attainable score, recomputed each time — the branch and bound's own order.
  while (detailedById.size < RECORDED_LOOKUPS) {
    let next: { id: string; ceiling: number } | null = null;
    for (const candidate of rank().candidates) {
      if (candidate.detailed || candidate.id === "" || detailedById.has(candidate.id)) continue;
      if (next === null || candidate.ceiling > next.ceiling) next = candidate;
    }
    if (next === null) break;
    await open(next.id);
  }

  const detailed = [...detailedById.values()];

  const detailedIds = new Set(detailed.map((release) => release.id));
  const fixture = {
    kind: "album",
    videos: scenario.videos,
    hints,
    candidates: searchResults.map((release) => {
      const full = detailed.find((candidate) => candidate.id === release.id);
      return full === undefined ? { release, detailed: false } : { release: full, detailed: true };
    }),
    groups: scoredGroups,
    lookedUp: [...detailedIds],
  };

  return { entries, fixture };
}

async function recordSingle(
  scenario: SingleScenario,
  known: ReadonlyMap<string, unknown> = new Map(),
  entries: CassetteEntry[] = [],
): Promise<{ entries: CassetteEntry[]; fixture: unknown }> {
  const written = new Set<string>();

  /**
   * Fetch a document, unless the cassette already carries it under that key.
   *
   * Two videos of the same scenario overlap heavily — the wide search is literally the same
   * request, and most of the lookups are the same recordings — and a re-record must not spend
   * a request, or risk a different answer, on a document that is already recorded.
   */
  async function document<T>(key: string, path: string, query: Record<string, string>): Promise<T> {
    const cached = known.get(key);
    const payload = cached ?? (await get<T>(path, query));
    if (!written.has(key)) {
      written.add(key);
      entries.push({ key, payload });
    }
    return payload as T;
  }

  async function forVideo(video: MatchVideo): Promise<unknown[]> {
    const title = video.ytTrack ?? video.title;

    // The same two searches the service makes: narrow to find the answer, wide to surface the
    // same-title recordings by other artists that the score has to be seen rejecting.
    const narrow = lucene.recordingQuery({
      title,
      artist: video.ytArtist ?? video.uploader ?? null,
      durationSeconds: video.durationSeconds,
    });
    const wide = lucene.recordingQuery({ title });
    /*
     * The artist on its own — the single path's half of the wizard's artist-only search.
     *
     * `recordingQuery` drops the empty title clause, so this is `artist:"…"` and nothing else.
     * It is recorded last and its results are merged like the other two, which means the
     * lookups a person browsing an artist would need are on the cassette too.
     */
    const artistAlone = lucene.recordingQuery({
      title: "",
      artist: video.ytArtist ?? video.uploader ?? null,
    });

    const merged: MbRecording[] = [];
    const seen = new Set<string>();
    for (const query of [narrow, wide, artistAlone]) {
      if (query === "") continue;
      const found = await document<SearchResult>(
        `search/recording?query=${query}&limit=${String(SEARCH_LIMIT)}&offset=0`,
        "recording",
        { query, limit: String(SEARCH_LIMIT), offset: "0" },
      );
      for (const recording of found.recordings ?? []) {
        if (recording.id === undefined || seen.has(recording.id)) continue;
        seen.add(recording.id);
        merged.push(recording);
      }
    }

    const candidates: unknown[] = [];
    for (const [index, recording] of merged.entries()) {
      if (recording.id === undefined) continue;
      let releases = (recording as { releases?: readonly MbRelease[] }).releases ?? [];
      if (index < RECORDED_LOOKUPS) {
        const full = await document<MbRecording & { releases?: readonly MbRelease[] }>(
          `recording/${recording.id}?inc=recordingBorrow`,
          `recording/${recording.id}`,
          { inc: INC.recordingBorrow },
        );
        if (full.releases !== undefined) releases = full.releases;
      }
      const credited = recording["artist-credit"] ?? [];
      candidates.push({
        id: recording.id,
        title: recording.title ?? "",
        artist: credited
          .map((entry) => `${entry.name ?? entry.artist?.name ?? ""}${entry.joinphrase ?? ""}`)
          .join("")
          .trim(),
        disambiguation: recording.disambiguation ?? "",
        lengthMs: recording.length ?? null,
        isrcs: recording.isrcs ?? [],
        searchScore: (recording as { score?: number }).score ?? null,
        releases,
      });
    }
    return candidates;
  }

  // The pure-engine fixture is the first video's scenario, and only that one.
  const candidates = await forVideo(scenario.video);
  for (const other of scenario.alsoVideos ?? []) await forVideo(other);

  return { entries, fixture: { kind: "single", video: scenario.video, candidates } };
}

